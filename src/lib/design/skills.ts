export function findSkill(key: string | undefined): DesignSkill | null {
  if (!key || key === 'none') return null;
  return DESIGN_SKILLS.find((s) => s.key === key) ?? null;
}

/** 화면에 미리 보여 줄 짧은 요약 — 전문을 다 읽을 필요는 없다. */
export function skillSummary(skill: DesignSkill): string[] {
  return skill.designMd
    .split('\n')
    .filter((line) => line.startsWith('- '))
    .slice(0, 4)
    .map((line) => line.slice(2).trim());
}
