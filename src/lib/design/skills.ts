/**
 * 디자인 스킬 — **"어떻게 생긴 서비스인가" 를 미리 정해 둔 묶음.**
 *
 * ## 왜 필요한가
 *
 * 화면마다 요청문을 아무리 잘 써도, 서비스 전체의 결이 정해져 있지 않으면 화면마다
 * 색·글꼴·모서리·간격이 제각각으로 나온다. 그런데 그 결을 매번 글로 쓰라고 하면
 * 기획자는 무엇을 써야 할지 모른다 — 그건 디자이너의 언어다.
 *
 * 그래서 자주 쓰이는 결을 미리 만들어 두고 **고르기만 하면 되게** 한다.
 *
 * ## 스티치에 어떻게 넘어가는가
 *
 * 스티치에는 디자인 시스템 개념이 있고, 만들 때 `designMd` 로 **지침 문서를 통째로**
 * 넣을 수 있다. 한 번 만들어 두면 이후 생성하는 화면이 전부 그것을 따른다.
 * 화면마다 "파란색 써 주세요" 를 반복하는 것과는 다르다.
 *
 * ## 지침을 쓸 때의 원칙
 *
 * **금지가 아니라 기준을 준다.** "그림자 쓰지 마세요" 보다 "면을 나눌 때는 그림자
 * 대신 1px 선을 씁니다" 가 낫다. 앞엣것은 대안 없이 막기만 해서, 도구가 다른
 * 이상한 방법을 찾는다.
 */

export interface DesignSkill {
  key: string;
  /** 화면에 보여 줄 이름. */
  name: string;
  /** 한 줄 설명 — 어떤 서비스에 맞는가. */
  what: string;
  /** 씨앗 색. 스티치가 이걸로 색 체계를 만든다. */
  color: string;
  headlineFont: string;
  bodyFont: string;
  /** ROUND_FOUR · ROUND_EIGHT · ROUND_TWELVE · ROUND_FULL */
  roundness: string;
  colorMode: 'LIGHT' | 'DARK';
  /** 스티치에 그대로 넘어가는 지침 문서. */
  designMd: string;
}

