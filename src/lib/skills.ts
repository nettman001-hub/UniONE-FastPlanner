/**
 * **기획 스킬** — 단계마다 "이런 식으로 써 달라" 를 적어 두는 것.
 *
 * ## 왜 필요한가
 *
 * AI 가 만들어 주는 것이 **우리 회사 양식이 아니라는 것**이 이 앱의 가장 큰
 * 약점이다. 매번 `AI로 수정하기` 로 같은 말을 반복하는 대신, 한 번 적어 두면
 * 다음부터 그 결을 따르게 한다.
 *
 * ## 바꿀 수 있는 것과 없는 것
 *
 * 산출물은 스키마로 모양이 고정돼 있고 화면이 그 모양을 전제로 그린다. 그래서
 * 스킬로 바꿀 수 있는 것은 **내용과 문체**이지 **구조**가 아니다.
 *
 * | 되는 것 | 안 되는 것 |
 * | --- | --- |
 * | "요구사항은 `~해야 한다` 로 끝낸다" | "PRD 에 리스크 섹션을 추가한다" |
 * | "우리 도메인 용어(회원/셀러)를 쓴다" | "우선순위를 P0~P4 다섯 단계로" |
 *
 * 오른쪽은 **저장할 자리가 없어서** 안 된다. 이걸 화면에도 적어 두지 않으면
 * "썼는데 반영이 안 된다" 는 불만이 나온다.
 *
 * ## 길이를 왜 막나
 *
 * 지침이 길면 그만큼 출력 여유가 줄어든다. 지금 기본 공급자는 출력 상한이
 * 넉넉하지 않아, 지침이 길수록 정작 만들 문서가 짧아진다.
 */

import { ARTIFACT_LABEL, type ArtifactKey } from './types';

export const SKILL_ARTIFACTS: ArtifactKey[] = ['prd', 'fs', 'ia', 'flow', 'wireframe'];

/** 지침 하나의 글자 수 상한. */
export const SKILL_MAX_CHARS = 4000;

export interface Skill {
  artifact: ArtifactKey;
  body: string;
  enabled: boolean;
  updatedAt?: string;
}

export type SkillMap = Partial<Record<ArtifactKey, string>>;

export function isSkillArtifact(value: unknown): value is ArtifactKey {
  return typeof value === 'string' && SKILL_ARTIFACTS.includes(value as ArtifactKey);
}

